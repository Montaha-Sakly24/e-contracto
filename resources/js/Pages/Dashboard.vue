<template>
    <div class="container">
        <div class="row-card">
            <v-card class="card">
                <v-card-title>Total Admins</v-card-title>
                <v-card-text>{{ totalAdmins }}</v-card-text>
            </v-card>

            <v-card class="card">
                <v-card-title>Total Users</v-card-title>
                <v-card-text>{{ totalUsers }}</v-card-text>
            </v-card>
        </div>
        <div class="row">
            <div id="LineChart" class="chart-container chart"></div>
        </div>
        <div class="row">
            <div id="chartdiv" class="chart-container chart"></div>
            <div id="piechart" class="chart-container chart"></div>
        </div>

        <div class="row">
            <div id="gaugechart" class="chart-container chart"></div>
            <div id="barchartdiv" class="chart-container chart"></div>
        </div>
    </div>
</template>

<script>
import axios from "axios";
import * as am4core from "@amcharts/amcharts4/core";
import * as am4charts from "@amcharts/amcharts4/charts";
import am4themes_animated from "@amcharts/amcharts4/themes/animated";

export default {
    data() {
        return {
            totalAdmins: null,
            totalUsers: null,
            signedContractsPercentage: 0,
            gaugeChart: null,
            contractsCountLastFourWeeks: [],
        };
    },
    mounted() {
        this.getAdminsCount();
        this.getSamplesUsersCount();
        this.getModelsCountByAdmin();
        this.getContractsCountBySampleUser();
        this.getSignedContractsPercentage();
        this.getContractsCountLastFourWeeks();
        this.getNewSampleUsersByMonth();
    },
    methods: {
        async getAdminsCount() {
            try {
                const instance = axios.create({
                    baseURL: "http://localhost:8000/api",
                });

                const response = await instance.get("/superadmin/admins/count");
                console.log("Admins count response:", response.data);
                this.totalAdmins = response.data;
            } catch (error) {
                console.error("Error fetching total admins:", error);
            }
        },
        async getSamplesUsersCount() {
            try {
                const instance = axios.create({
                    baseURL: "http://localhost:8000/api",
                });
                const response = await instance.get("/superadmin/users/count");
                console.log("Users count response:", response.data);
                this.totalUsers = response.data;
            } catch (error) {
                console.error("Error fetching total users:", error);
            }
        },
        async getModelsCountByAdmin() {
            try {
                const instance = axios.create({
                    baseURL: "http://localhost:8000/api",
                });
                const response = await instance.get("/superadmin/models/count");
                const data = response.data;

                // Transform the data to the required structure
                const chartData = data.map((item) => ({
                    name: item.name, // Admin name
                    points: item.total_models, // Number of models
                }));

                // Create chart instance
                const chart = am4core.create("chartdiv", am4charts.XYChart);
                chart.data = chartData;

                // Apply theme
                am4core.useTheme(am4themes_animated);
                // Ajouter un titre au graphique
                const title = chart.titles.create();
                title.text = "Contract Models Generated by Each Admin";
                title.fontSize = 20;
                title.marginBottom = 30;
                // Create axes
                const categoryAxis = chart.xAxes.push(
                    new am4charts.CategoryAxis()
                );
                categoryAxis.renderer.grid.template.location = 0;
                categoryAxis.dataFields.category = "name";
                categoryAxis.renderer.minGridDistance = 60;
                categoryAxis.renderer.labels.template.verticalCenter = "middle";
                categoryAxis.renderer.labels.template.fill =
                    am4core.color("#333");

                categoryAxis.title.text = "Admins";
                // categoryAxis.title.rotation = 0;
                categoryAxis.title.align = "center";
                // categoryAxis.title.valign = "top";
                // categoryAxis.title.dy = -40;
                categoryAxis.title.fontWeight = 600;

                const valueAxis = chart.yAxes.push(new am4charts.ValueAxis());
                valueAxis.renderer.labels.template.fill = am4core.color("#333");
                valueAxis.renderer.grid.template.stroke = am4core.color("#aaa");
                valueAxis.renderer.grid.template.strokeOpacity = 0.5;
                valueAxis.min = 0;
                valueAxis.renderer.minGridDistance = 30;
                valueAxis.title.text = "Contract Models Number";
                // valueAxis.title.rotation = 0;
                // valueAxis.title.align = "center";
                // valueAxis.title.valign = "top";

                valueAxis.title.fontWeight = 600;

                // Create series
                const series = chart.series.push(new am4charts.ColumnSeries());
                series.dataFields.valueY = "points";
                series.dataFields.categoryX = "name";
                series.columns.template.tooltipText =
                    "{categoryX}: [bold]{valueY}[/b]";

                // Add bullets
                const bullet = series.bullets.push(new am4charts.Bullet());
                const image = bullet.createChild(am4core.Image);
                image.horizontalCenter = "middle";
                image.verticalCenter = "bottom";
                image.dy = 20;
                image.y = am4core.percent(100);
                image.propertyFields.href = "bullet";
                image.tooltipText = series.columns.template.tooltipText;
                image.filters.push(new am4core.DropShadowFilter());

                // Set colors
                series.columns.template.adapter.add(
                    "fill",
                    function (fill, target) {
                        return chart.colors.getIndex(target.dataItem.index);
                    }
                );
                this.$options.beforeUnmount = () => {
                    chart.dispose();
                };
            } catch (error) {
                console.error("Error fetching models count by admin:", error);
            }
        },

        async getContractsCountBySampleUser() {
            try {
                const instance = axios.create({
                    baseURL: "http://localhost:8000/api",
                });
                const response = await instance.get(
                    "/superadmin/contracts/count"
                );
                console.log(
                    "Contracts count by sample users response:",
                    response.data
                );

                const pieChartData = response.data.map((item) => ({
                    country: item.name,
                    litres: item.total_contracts,
                }));

                const pieChart = am4core.create("piechart", am4charts.PieChart);
                pieChart.data = pieChartData;

                const title = pieChart.titles.create();
                title.text = "Contracts Generated by Each Sample User";
                title.fontSize = 20;
                title.fontFamily = "Arial";
                title.fill = am4core.color("#333");
                title.marginTop = 15;

                var pieSeries = pieChart.series.push(new am4charts.PieSeries());
                pieSeries.dataFields.value = "litres";
                pieSeries.dataFields.category = "country";
                pieSeries.labels.template.disabled = true;
                pieSeries.ticks.template.disabled = true;
                pieChart.legend = new am4charts.Legend();
            } catch (error) {
                console.error(
                    "Error fetching contracts count by sample users:",
                    error
                );
            }
        },

        async getSignedContractsPercentage() {
            try {
                const instance = axios.create({
                    baseURL: "http://localhost:8000/api",
                });
                const response = await instance.get(
                    "/superadmin/contracts/signed-percentage"
                );
                console.log(
                    "Signed contracts percentage response:",
                    response.data
                );
                this.signedContractsPercentage =
                    response.data.signed_percentage;

                this.updateGaugeChart(response.data.signed_percentage);
            } catch (error) {
                console.error(
                    "Error fetching signed contracts percentage:",
                    error
                );
            }
        },

        updateGaugeChart(signedPercentage) {
            if (this.gaugeChart) {
                this.gaugeChart.dispose();
            }

            var chart = am4core.create("gaugechart", am4charts.GaugeChart);
            // Ajouter un titre au graphique
            const title = chart.titles.create();
            title.text = "Signed Contracts Percentage";
            title.fontSize = 20;

            // Create the gauge axis
            var axis = chart.xAxes.push(new am4charts.ValueAxis());
            axis.min = 0;
            axis.max = 100;
            axis.strictMinMax = true;
            axis.renderer.radius = am4core.percent(80);
            axis.renderer.inside = true;
            axis.renderer.line.strokeOpacity = 1;
            axis.renderer.ticks.template.disabled = false;
            axis.renderer.ticks.template.strokeOpacity = 1;
            axis.renderer.ticks.template.length = 10;
            axis.renderer.grid.template.disabled = true;
            axis.renderer.labels.template.radius = 40;
            axis.renderer.labels.template.adapter.add("text", function (text) {
                return text + "%";
            });

            // Set up the hand for the gauge
            var hand = chart.hands.push(new am4charts.ClockHand());
            hand.axis = axis;
            hand.innerRadius = am4core.percent(20);
            hand.startWidth = 10;
            hand.pin.disabled = true;

            // Set the value for the hand without animation
            hand.value = signedPercentage;

            // Store the chart instance in a variable for disposal later
            this.gaugeChart = chart;
        },

        async getContractsCountLastFourWeeks() {
            try {
                const instance = axios.create({
                    baseURL: "http://localhost:8000/api",
                });
                const response = await instance.get(
                    "/superadmin/contracts/count-last-four-weeks"
                );
                const data = response.data;

                // Create chart instance
                const chart = am4core.create("barchartdiv", am4charts.XYChart);
                chart.data = data;

                // Apply theme
                am4core.useTheme(am4themes_animated);

                // Ajouter un titre au graphique
                const title = chart.titles.create();
                title.text = "Contracts Generated For The Last Four Weeks";
                title.fontSize = 20;
                title.marginBottom = 30;
                // Create axes
                const categoryAxis = chart.xAxes.push(
                    new am4charts.CategoryAxis()
                );
                categoryAxis.renderer.grid.template.location = 0;
                categoryAxis.dataFields.category = "week";
                categoryAxis.renderer.minGridDistance = 60;
                categoryAxis.renderer.labels.template.verticalCenter = "middle";
                categoryAxis.renderer.labels.template.fill =
                    am4core.color("#333");
                categoryAxis.title.text = "Week";
                categoryAxis.title.align = "center";
                categoryAxis.title.fontWeight = 600;

                const valueAxis = chart.yAxes.push(new am4charts.ValueAxis());
                valueAxis.renderer.labels.template.fill = am4core.color("#333");
                valueAxis.renderer.grid.template.stroke = am4core.color("#aaa");
                valueAxis.renderer.grid.template.strokeOpacity = 0.5;
                valueAxis.min = 0;
                valueAxis.renderer.minGridDistance = 30;
                valueAxis.title.text = "Contracts Count";
                valueAxis.title.fontWeight = 600;

                // Create series
                const series = chart.series.push(new am4charts.ColumnSeries());
                series.dataFields.valueY = "contracts_count";
                series.dataFields.categoryX = "weeks";
                series.columns.template.tooltipText =
                    "{categoryX}: [bold]{valueY}[/b]";

                // Set colors
                series.columns.template.adapter.add(
                    "fill",
                    function (fill, target) {
                        return chart.colors.getIndex(target.dataItem.index);
                    }
                );

                this.$options.beforeUnmount = () => {
                    chart.dispose();
                };
            } catch (error) {
                console.error(
                    "Error fetching contracts count for last four weeks:",
                    error
                );
            }
        },
        async getNewSampleUsersByMonth() {
            try {
                const instance = axios.create({
                    baseURL: "http://localhost:8000/api",
                });
                const response = await instance.get(
                    "/superadmin/users/new-sample-users-by-month"
                );
                const data = response.data;

                // Convertir les données au format adapté pour le graphique
                const chartData = data.map((item) => ({
                    date: new Date(item.year, item.month - 1), // Soustraire 1 car les mois sont indexés de 0 à 11
                    count: item.count,
                }));

                // Créer une instance du graphique
                const chart = am4core.create("LineChart", am4charts.XYChart);
                chart.data = chartData;

                // Ajouter un titre au graphique
                const title = chart.titles.create();
                title.text = "New Sample Users Count by Month";
                title.fontSize = 20;
                title.marginBottom = 15;

                // Créer les axes
                const dateAxis = chart.xAxes.push(new am4charts.DateAxis());
                dateAxis.dataFields.date = "date";
                dateAxis.renderer.grid.template.location = 0;
                dateAxis.renderer.labels.template.fill = am4core.color("#333");
                dateAxis.title.text = "Date";
                dateAxis.title.align = "center";
                dateAxis.title.fontWeight = 600;

                const valueAxis = chart.yAxes.push(new am4charts.ValueAxis());
                valueAxis.renderer.labels.template.fill = am4core.color("#333");
                valueAxis.renderer.grid.template.stroke = am4core.color("#aaa");
                valueAxis.renderer.grid.template.strokeOpacity = 0.5;
                valueAxis.min = 0;
                valueAxis.renderer.minGridDistance = 30;
                valueAxis.title.text = "New Sample Users";
                valueAxis.title.fontWeight = 600;

                // Créer la série de données
                const series = chart.series.push(new am4charts.LineSeries());
                series.dataFields.valueY = "count";
                series.dataFields.dateX = "date";
                series.strokeWidth = 3;
                series.tooltipText = "{categoryX}: [bold]{valueY}[/b]";

                // Ajouter un marqueur
                const bullet = series.bullets.push(new am4charts.Bullet());
                const image = bullet.createChild(am4core.Image);
                image.href = "https://www.amcharts.com/lib/images/star.svg";
                image.width = 30;
                image.height = 30;
                image.horizontalCenter = "middle";
                image.verticalCenter = "middle";

                this.$options.beforeUnmount = () => {
                    chart.dispose();
                };
            } catch (error) {
                console.error(
                    "Error fetching new sample users by month:",
                    error
                );
            }
        },
    },
};
</script>
